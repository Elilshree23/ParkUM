public class Action {
    String actionType;
    String licensePlate;
    String ownerName;
    String parkingSlot;

    public Action(String actionType, String licensePlate, String ownerName, String parkingSlot) {
        this.actionType = actionType;
        this.licensePlate = licensePlate;
        this.ownerName = ownerName;
        this.parkingSlot = parkingSlot;
    }
}
